export type ErrorCode = keyof typeof ERRORS;
export const ERROR_CODES = Object.keys(ERRORS) as ErrorCode[];

export interface ErrorBody {
  error: { code: ErrorCode; message: string; retryable: boolean; details: Record<string, unknown> };
}

export class ApiError extends Error {
  readonly code: ErrorCode;
  readonly details: Record<string, unknown>;
  constructor(code: ErrorCode, message: string, details: Record<string, unknown> = {}) {
    super(message);
    this.name = "ApiError";
    this.code = code;
    this.details = details;
  }
  get status(): number {
    return ERRORS[this.code].status;
  }
  body(): ErrorBody {
    return errorBody(this.code, this.message, this.details);
  }
}

export function errorBody(code: ErrorCode, message: string, details: Record<string, unknown> = {}): ErrorBody {
  return { error: { code, message, retryable: ERRORS[code].retryable, details } };
}

export const README_START = "<!-- ERRORS:START (generated by npm run docs:errors; do not edit) -->";
export const README_END = "<!-- ERRORS:END -->";

export function errorTableMarkdown(): string {
  const rows = ERROR_CODES.map((c) => `| \`${c}\` | ${ERRORS[c].status} | ${ERRORS[c].retryable ? "yes" : "no"} | ${ERRORS[c].description} |`);
  return ["| Code | HTTP | Retryable | Meaning |", "|---|---|---|---|", ...rows].join("\n");
}

/** Replace the generated region of a README. Throws when the markers are missing. */
export function renderReadme(readme: string): string {
  const a = readme.indexOf(README_START);
  const b = readme.indexOf(README_END);
  if (a < 0 || b < a) throw new Error("README.md has no ERRORS:START / ERRORS:END markers");
  return readme.slice(0, a) + README_START + "\n" + errorTableMarkdown() + "\n" + readme.slice(b);
}
