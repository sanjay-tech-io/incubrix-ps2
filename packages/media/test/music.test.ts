import { createHash } from "node:crypto";
import { describe, expect, it } from "vitest";
import { BUILTIN_MUSIC_SHA256, builtinMusicWav } from "../src/index.ts";

describe("built-in music", () => {
  it("is generated by arithmetic and its bytes never change (sha256 pinned)", () => {
    const b = builtinMusicWav();
    expect(createHash("sha256").update(b).digest("hex")).toBe(BUILTIN_MUSIC_SHA256);
    expect(Buffer.from(b.subarray(0, 4)).toString()).toBe("RIFF");
  });
});
